/* ==========================================================================
   MODAL EVENT HANDLERS
   ========================================================================== */
function setupModalListeners() {
  const modal = document.getElementById('project-modal');
  const closeBtn = document.getElementById('modal-close-btn');
  const dismissBtn = document.getElementById('modal-dismiss-btn');

  if (!modal) return;

  const closeModal = () => {
    modal.classList.remove('open');
    modal.setAttribute('aria-hidden', 'true');
    document.body.style.overflow = ''; // Re-enable background scrolling
    closeModalScreenshotPreview();
    closeModalAboutDetails();
  };

  // Close triggers
  closeBtn.addEventListener('click', closeModal);
  if (dismissBtn) {
    dismissBtn.addEventListener('click', closeModal);
  }

  // Close on clicking the backdrop overlay
  modal.addEventListener('click', (e) => {
    if (e.target === modal) {
      closeModal();
    }
  });

  // Close on Escape key press
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') {
      if (modal.classList.contains('open')) {
        closeModal();
      }
      // Close any open in-card previews
      const openPreviews = document.querySelectorAll('.ps-preview-overlay.open');
      openPreviews.forEach(preview => {
        const idx = preview.id.split('-').pop();
        closeInCardPreview(parseInt(idx));
      });
    }
  });

  // Swipe handler setup for mobile gestures on the modal screenshot preview zone
  const modalPreviewOverlay = document.getElementById('modal-preview-overlay');
  if (modalPreviewOverlay) {
    let mStartX = 0;
    modalPreviewOverlay.addEventListener('touchstart', (e) => {
      mStartX = e.touches[0].clientX;
    }, { passive: true });

    modalPreviewOverlay.addEventListener('touchend', (e) => {
      const endX = e.changedTouches[0].clientX;
      const diff = mStartX - endX;
      // Threshold: 50px
      if (Math.abs(diff) > 50) {
        if (diff > 0) {
          navigateModalPreview(1);
        } else {
          navigateModalPreview(-1);
        }
      }
    }, { passive: true });
  }
}

