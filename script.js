function openInCardPreview(projectIndex, screenshotIndex, event) {
  if (event) event.stopPropagation(); // Prevent launching project detail drawer
  
  const project = projectsData[projectIndex];
  if (!project || !project.screenshots || project.screenshots.length === 0) return;

  // Set the active preview state
  activePreviewState[projectIndex] = {
    currentIdx: screenshotIndex,
    urls: project.screenshots
  };

  const overlay = document.getElementById(`ps-preview-${projectIndex}`);
  if (!overlay) return;

  overlay.classList.add('open');
  overlay.setAttribute('aria-hidden', 'false');
  
  updateInCardPreview(projectIndex);
}

function closeInCardPreview(projectIndex, event) {
  if (event) event.stopPropagation(); // Prevent card click triggers

  const overlay = document.getElementById(`ps-preview-${projectIndex}`);
  if (!overlay) return;

  overlay.classList.remove('open');
  overlay.setAttribute('aria-hidden', 'true');
  
  // Clear state for this card
  delete activePreviewState[projectIndex];
}

function navigatePreview(projectIndex, direction, event) {
  if (event) event.stopPropagation(); // Prevent overlay dismiss or page clicks

  const state = activePreviewState[projectIndex];
  if (!state) return;

  let newIdx = state.currentIdx + direction;
  
  // Cap boundary checks (0 to length - 1)
  if (newIdx < 0) {
    newIdx = 0;
  } else if (newIdx >= state.urls.length) {
    newIdx = state.urls.length - 1;
  }

  state.currentIdx = newIdx;
  updateInCardPreview(projectIndex);
}

function updateInCardPreview(projectIndex) {
  const state = activePreviewState[projectIndex];
  if (!state) return;

  const img = document.getElementById(`ps-preview-img-${projectIndex}`);
  const prevArrow = document.getElementById(`ps-prev-arrow-${projectIndex}`);
  const nextArrow = document.getElementById(`ps-next-arrow-${projectIndex}`);

  if (!img) return;

  // Load active screenshot
  img.src = state.urls[state.currentIdx];

  // Show/Hide Left Arrow depending on boundary
  if (prevArrow) {
    if (state.currentIdx === 0) {
      prevArrow.style.visibility = 'hidden';
    } else {
      prevArrow.style.visibility = 'visible';
    }
  }

  // Show/Hide Right Arrow depending on boundary
  if (nextArrow) {
    if (state.currentIdx === state.urls.length - 1) {
      nextArrow.style.visibility = 'hidden';
    } else {
      nextArrow.style.visibility = 'visible';
    }
  }
}

